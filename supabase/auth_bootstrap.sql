create policy storage_insert_member_files on storage.objects
  for insert with check (
    bucket_id in ('logos', 'files')
    and public.is_tenant_member((storage.foldername(name))[1]::uuid)
  );

drop policy if exists storage_update_member_files on storage.objects;
create policy storage_update_member_files on storage.objects
  for update using (
    bucket_id in ('logos', 'files')
    and public.is_tenant_member((storage.foldername(name))[1]::uuid)
  )
  with check (
    bucket_id in ('logos', 'files')
    and public.is_tenant_member((storage.foldername(name))[1]::uuid)
  );
