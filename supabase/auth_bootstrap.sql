create or replace function public.bootstrap_user_workspace(
  p_user_id uuid,
  p_email text,
  p_company_name text default null
)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_tenant_id uuid;
  v_company_name text;
begin
  select m.tenant_id
    into v_tenant_id
    from public.memberships m
    where m.user_id = p_user_id
    limit 1;

  if v_tenant_id is not null then
    return v_tenant_id;
  end if;

  v_company_name := nullif(trim(coalesce(p_company_name, '')), '');
  if v_company_name is null then
    v_company_name := nullif(split_part(coalesce(p_email, ''), '@', 1), '');
  end if;
  if v_company_name is null then
    v_company_name := 'My company';
  end if;

  insert into public.tenants (name, created_by)
  values (v_company_name, p_user_id)
  returning id into v_tenant_id;

  insert into public.memberships (tenant_id, user_id, role)
  values (v_tenant_id, p_user_id, 'owner')
  on conflict (tenant_id, user_id) do nothing;

  insert into public.branding (
    tenant_id,
    company_name,
    primary_color,
    background_color,
    accent_color,
    domain_status
  )
  values (
    v_tenant_id,
    v_company_name,
    '#111111',
    '#ffffff',
    '#6366f1',
    'none'
  )
  on conflict (tenant_id) do nothing;

  return v_tenant_id;
end;
$$;

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  perform public.bootstrap_user_workspace(
    new.id,
    new.email,
    new.raw_user_meta_data ->> 'company_name'
  );

  if to_regprocedure('public.link_platform_admin_for_user(uuid,text)') is not null then
    perform public.link_platform_admin_for_user(new.id, new.email);
  end if;

  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

create or replace function public.ensure_user_tenant()
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user_id uuid := auth.uid();
  v_email text;
  v_company_name text;
begin
  if v_user_id is null then
    raise exception 'Not authenticated';
  end if;

  select u.email, u.raw_user_meta_data ->> 'company_name'
    into v_email, v_company_name
    from auth.users u
    where u.id = v_user_id;

  if v_email is null then
    raise exception 'User not found';
  end if;

  return public.bootstrap_user_workspace(v_user_id, v_email, v_company_name);
end;
$$;

drop function if exists public.qr_analytics(uuid);

create function public.qr_analytics(p_qr uuid)
returns table (
  total bigint,
  last_7 bigint,
  by_day jsonb,
  by_device jsonb
)
language sql
security definer
set search_path = public
stable
as $$
  with target as (
    select q.id, q.tenant_id
    from public.qr_codes q
    where q.id = p_qr
      and public.is_tenant_member(q.tenant_id)
  ),
  scan_rows as (
    select s.*
    from public.scans s
    join target t on t.id = s.qr_id
  ),
  day_rows as (
    select to_char(s.scanned_at::date, 'YYYY-MM-DD') as day, count(*) as n
    from scan_rows s
    where s.scanned_at >= now() - interval '30 days'
    group by s.scanned_at::date
  ),
  device_rows as (
    select coalesce(device, 'Unknown') as device, count(*) as n
    from scan_rows
    group by coalesce(device, 'Unknown')
  )
  select
    (select count(*) from scan_rows)::bigint as total,
    (select count(*) from scan_rows where scanned_at >= now() - interval '7 days')::bigint as last_7,
    coalesce((select jsonb_object_agg(day, n order by day) from day_rows), '{}'::jsonb) as by_day,
    coalesce((select jsonb_object_agg(device, n order by device) from device_rows), '{}'::jsonb) as by_device;
$$;

revoke all on function public.bootstrap_user_workspace(uuid, text, text) from public;
grant execute on function public.ensure_user_tenant() to authenticated;
grant execute on function public.qr_analytics(uuid) to authenticated;

