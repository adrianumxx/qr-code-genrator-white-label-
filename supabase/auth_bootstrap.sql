-- QR Studio database + auth bootstrap
-- Apply this in Supabase SQL Editor or via Supabase migrations.

create extension if not exists pgcrypto;

create table if not exists public.tenants (
  id uuid primary key default gen_random_uuid(),
  name text not null default 'My company',
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.memberships (
  id uuid primary key default gen_random_uuid(),
  tenant_id uuid not null references public.tenants(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  role text not null default 'owner',
  created_at timestamptz not null default now(),
  unique (tenant_id, user_id)
);

create table if not exists public.branding (
  tenant_id uuid primary key references public.tenants(id) on delete cascade,
  company_name text,
  primary_color text not null default '#111111',
  background_color text not null default '#ffffff',
  accent_color text not null default '#6366f1',
  logo_url text,
  custom_domain text unique,
  domain_status text not null default 'none',
  domain_verified_at timestamptz,
  domain_cf_id text,
  updated_at timestamptz not null default now()
);

create table if not exists public.qr_codes (
  id uuid primary key default gen_random_uuid(),
  tenant_id uuid not null references public.tenants(id) on delete cascade,
  created_by uuid references auth.users(id) on delete set null,
  title text not null default 'Untitled QR',
  type text not null default 'url',
  content text,
  is_dynamic boolean not null default false,
  short_code text unique,
  destination text,
  design jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.scans (
  id bigint generated by default as identity primary key,
  qr_id uuid not null references public.qr_codes(id) on delete cascade,
  tenant_id uuid not null references public.tenants(id) on delete cascade,
  ip text,
  country text,
  device text,
  os text,
  browser text,
  referer text,
  user_agent text,
  scanned_at timestamptz not null default now()
);

create index if not exists memberships_user_id_idx on public.memberships(user_id);
create index if not exists memberships_tenant_id_idx on public.memberships(tenant_id);
create index if not exists qr_codes_tenant_id_idx on public.qr_codes(tenant_id);
create index if not exists qr_codes_short_code_idx on public.qr_codes(short_code);
create index if not exists scans_qr_id_scanned_at_idx on public.scans(qr_id, scanned_at desc);
create index if not exists scans_tenant_id_scanned_at_idx on public.scans(tenant_id, scanned_at desc);

create or replace function public.is_tenant_member(p_tenant_id uuid)
returns boolean
language sql
security definer
set search_path = public
stable
as $$
  select exists (
    select 1
    from public.memberships m
    where m.tenant_id = p_tenant_id
      and m.user_id = auth.uid()
  );
$$;

